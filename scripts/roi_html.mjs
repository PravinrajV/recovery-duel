// T18 fallback (no Slack connection yet): static HTML ROI report from T15 tenant scenario results.
// Money math comes only from rules/rules.js (deductibleRefund, ledgerSummary). SYNTHETIC data, SIMULATED carrier.
// Usage: node scripts/roi_html.mjs [docs/runs/T15_results.json] [docs/roi_report.html]
import fs from 'node:fs';
import { createRequire } from 'node:module';
const R = createRequire(import.meta.url)('../rules/rules.js');
const resPath = process.argv[2] || 'docs/runs/T15_results.json';
const outPath = process.argv[3] || 'docs/roi_report.html';
const results = JSON.parse(fs.readFileSync(resPath));
const claims = JSON.parse(fs.readFileSync('data/store/claims.json')).claims;
const byId = Object.fromEntries(claims.map(c => [c.claim_id, c]));
const scen = JSON.parse(fs.readFileSync('tests/scenarios/scenarios.json'));
const spec = Object.fromEntries((Array.isArray(scen) ? scen : scen.scenarios).map(s => [s.id, s]));
const desc = Object.fromEntries(((j) => Array.isArray(j) ? j : j.scenarios)(JSON.parse(fs.readFileSync('data/scenarios.json'))).map(x => [x.id, x.description]));
const esc = s => String(s ?? '').replace(/[&<>"]/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[ch]));
const usd = n => '$' + Math.round(Number(n) || 0).toLocaleString('en-US');
const entries = [], rows = [];
let paidBase = 0;
for (const id of Object.keys(results).sort()) {
  const r = results[id]; const claimId = r.top || Object.keys(r.rank || {})[0] || 'NONE';
  const c = byId[claimId] || (spec[id]?.claims || []).find(x => x.claim_id === claimId) || {};
  const won = r.neg === 'SETTLED' && r.approval === 'APPROVED';
  const d = R.deductibleRefund(c.paid_amount, c.deductible, won ? r.amount : 0);
  paidBase += Number(c.paid_amount) || 0;
  entries.push({ claim_id: claimId, status: r.neg, approval: r.approval || 'NOT_REQUIRED', amount: Number(r.amount) || 0,
    refund: d.refund, insurer_net: won ? d.insurer_net : 0 });
  rows.push(`<tr><td>${esc(id)}</td><td>${esc(desc[id] || '')}</td><td>${esc(claimId)}</td><td>${esc(r.stopped ? 'KILL_SWITCH' : r.neg)}</td><td>${esc(r.rounds ?? '')}</td><td>${r.amount ? usd(r.amount) : ''}</td><td>${esc(r.tier || '')}</td><td>${esc(r.approval || '')}</td><td>${won ? usd(d.refund) : ''}</td><td>${won ? usd(d.insurer_net) : ''}</td><td>${r.pass ? 'PASS' : 'FAIL'}</td></tr>`);
}
const s = R.ledgerSummary(entries, paidBase);
const pass = Object.values(results).filter(r => r.pass).length;
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Recovery Duel ROI report (synthetic)</title>
<style>body{font:15px system-ui,sans-serif;margin:2rem;max-width:1200px;color:#222}table{border-collapse:collapse;width:100%}td,th{border:1px solid #ccc;padding:4px 8px;text-align:left}th{background:#f3f3f3}.k{display:inline-block;margin:0 1.5rem 1rem 0}.k b{display:block;font-size:1.6rem}.note{color:#666;font-size:13px}</style></head><body>
<h1>Recovery Duel ROI report</h1>
<p class="note">SYNTHETIC claims, SIMULATED counterparty carrier. Generated by scripts/roi_html.mjs from ${esc(resPath)} (tenant debug runs). Amounts computed by rules/rules.js.</p>
<div class="k"><b>${pass}/${Object.keys(results).length}</b>scenarios pass</div>
<div class="k"><b>${usd(s.recovered)}</b>recovered (settled and approved)</div>
<div class="k"><b>${usd(s.refunds)}</b>deductible refunds to policyholders</div>
<div class="k"><b>${usd(s.insurer_net)}</b>insurer net</div>
<div class="k"><b>${s.reconciles ? 'Yes' : 'NO'}</b>ledger reconciles</div>
<p>Recovery ratio over claims paid in these scenarios: <b>${(100 * (s.recovery_ratio || 0)).toFixed(1)}%</b>. Benchmark indicator: salvage plus subrogation is 4.5% of net claims paid industry-wide (Bisco and Fier, NAIC Journal of Insurance Regulation, 2023, <a href="${esc(R.BENCHMARK?.source || 'https://content.naic.org/sites/default/files/cipr-jir-2023-2.pdf')}">source</a>). Not a like-for-like comparison: the scenarios are a hand-picked test set.</p>
<table><tr><th>Scenario</th><th>Description</th><th>Claim</th><th>Outcome</th><th>Rounds</th><th>Settled</th><th>Tier</th><th>Approval</th><th>Refund</th><th>Insurer net</th><th>Test</th></tr>
${rows.join('\n')}</table></body></html>
`;
fs.writeFileSync(outPath, html);
console.log(JSON.stringify({ out: outPath, pass, recovered: s.recovered, refunds: s.refunds, insurer_net: s.insurer_net, reconciles: s.reconciles }));
if (!s.reconciles) process.exit(1);
